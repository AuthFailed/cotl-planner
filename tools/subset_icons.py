"""Cut Phosphor's icon fonts and CSS down to the icons the page names, into src/icons/.

Every icon class is spelled out in full in index.html and src/*.ts; run again after adding one
(tools/test.mjs fails until then):
    uv run --with fonttools --with brotli tools/subset_icons.py
"""
import re
from pathlib import Path

from fontTools import subset

root = Path(__file__).resolve().parent.parent
web = root / "node_modules/@phosphor-icons/web/src"
out = root / "src/icons"
out.mkdir(exist_ok=True)

sources = [root / "index.html", *sorted((root / "src").glob("*.ts"))]
used = {n for f in sources for n in re.findall(r"\bph-[a-z0-9-]+", f.read_text())}

css = []
for weight, font in [("regular", "Phosphor"), ("fill", "Phosphor-Fill")]:
    text = (web / weight / "style.css").read_text()
    rule = re.compile(r"\.ph(?:-fill)?\.(ph-[a-z0-9-]+):before \{[^}]*\}\s*")
    text = rule.sub(lambda m: m.group(0) if m.group(1) in used else "", text)
    text = re.sub(r"src:[^;]*;", f'src: url("./{font}.woff2") format("woff2");', text, count=1)
    codepoints = [int(c, 16) for c in re.findall(r'content: "\\([0-9a-f]+)"', text)]

    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = []  # the CSS picks glyphs by codepoint, not by ligature
    font_file = subset.load_font(str(web / weight / f"{font}.ttf"), options)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font_file)
    subset.save_font(font_file, str(out / f"{font}.woff2"), options)
    css.append(text)

(out / "icons.css").write_text(
    f"/* Generated by tools/subset_icons.py from @phosphor-icons/web: only the icons the page uses. */\n{''.join(css)}")
print(f"{len(used)} icon names -> {out.relative_to(root)}")
